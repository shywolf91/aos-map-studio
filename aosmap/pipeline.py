"""Export + validation pipeline for a Scene. Used by scenes/diagnostic.py.

Stages (each writes an artefact; statuses follow the project ladder):
  generated -> exported (.vxl/.txt) -> parser-validated (own reader + pyspades 1.4.2 reader,
  byte-identical regeneration) -> runtime-emulated (piqueserver 1.4.2 code run against the file:
  VXLData collapse, arena Gate, push colour test, Map loader) -> rendered previews.
Server-loaded / client-inspected / playtested are separate, later stages.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import time

import numpy as np

from .meta import map_txt, check_map_txt
from .render import top_down, isometric, contact_sheet
from .validate import validate, floating_components
from .vxl import read_vxl, write_vxl


def _sha(b):
    return hashlib.sha256(b).hexdigest()


def run_diagnostic(build_fn, out_dir):
    """build_fn() -> Scene. Called twice to prove deterministic output."""
    os.makedirs(out_dir, exist_ok=True)
    scene = build_fn()
    mk = scene.markers
    res = {'scene': scene.name, 'seed': scene.seed, 'generated_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}
    t = time.time()

    # ---------------- generate + export
    vm = scene.to_voxelmap()
    data = write_vxl(vm)                                    # strict: errors on uncoloured surfaces
    vxl_path = os.path.join(out_dir, f'{scene.name}.vxl')
    open(vxl_path, 'wb').write(data)
    res['vxl'] = {'path': vxl_path, 'bytes': len(data), 'sha256': _sha(data)}
    txt = map_txt(
        name=scene.name, author='aosmap', version='0.1',
        description='aosmap exporter diagnostic scene - not a gameplay map',
        header=f'seed {scene.seed}; generated by scenes/diagnostic.py',
        fog=(150, 190, 215),
        extensions={'water_damage': 0,
                    'arena_gates': tuple(g['seed'] for g in mk['gates']),
                    'arena_blue_spawns': tuple(mk['spawns_blue'][:1]),
                    'arena_green_spawns': tuple(mk['spawns_green'][:1])},
        spawns={0: mk['spawns_blue'], 1: mk['spawns_green']},
        entities=mk['entities'])
    txt_path = os.path.join(out_dir, f'{scene.name}.txt')
    open(txt_path, 'w').write(txt)
    res['txt'] = {'path': txt_path}

    # ---------------- determinism: rebuild from scratch, compare bytes
    data2 = write_vxl(build_fn().to_voxelmap())
    res['deterministic_rebuild_identical'] = (data2 == data)

    # ---------------- parser validation (own reader)
    back, rep = read_vxl(data)
    res['reader'] = {'ok': rep.ok, 'spans': rep.spans, 'empty_top_runs': rep.empty_top_runs,
                     'issues': rep.issues[:10]}
    res['reader_occupancy_equal'] = bool(np.array_equal(back.solid, vm.solid))
    surf = back.colored
    res['reader_colours_equal'] = bool(np.array_equal(back.color[surf], vm.color[surf]))

    # ---------------- parser validation (pyspades 1.4.2, independent C++ loader)
    from pyspades.vxl import VXLData
    pys = VXLData(io.BytesIO(data))
    regen = pys.generate()
    res['pyspades_regenerate_byte_identical'] = (regen == data)
    probes = {'ground': (200, 260, 58), 'roof_top': (256, 254, 46),
              'room_interior_air': (233, 273, 55), 'spire_z0': (341, 301, 0),
              'water_z62_air': (100, 100, 62), 'water_z63_solid': (100, 100, 63),
              'gate_A': (304, 270, 53)}
    res['pyspades_probes'] = {k: {'solid': bool(pys.get_solid(*p)), 'rgb': pys.get_color(*p)}
                              for k, p in probes.items()}

    # ---------------- static validation
    vrep = validate(vm, expect_floating=mk['expect_floating'], gates=mk['gates'],
                    spawns=[{'name': f'blue{i}', 'xyz': p} for i, p in enumerate(mk['spawns_blue'])] +
                           [{'name': f'green{i}', 'xyz': p} for i, p in enumerate(mk['spawns_green'])],
                    team_colors=((0, 0, 255), (0, 255, 0)))
    # gate material check: every voxel of the authored gate must be in arena's selection
    from scipy import ndimage
    from .validate import arena_gate_selection, FACE6
    gid = scene._ids[mk['gate_material']]
    lab, _ = ndimage.label(scene.mat == gid, structure=FACE6)
    for g in mk['gates']:
        comp = int((lab == lab[g['seed']]).sum())
        sel = len(arena_gate_selection(vm, g['seed'])[0])
        if comp != sel:
            lvl = 'info' if g.get('expect_failure') else 'error'
            msg = (f"{g['name']}: authored gate has {comp} voxels but arena selects {sel}; "
                   f"{comp - sel} would never be removed (gate thicker than 2 hides voxels)")
            if lvl == 'info':
                msg += ' [EXPECTED FAILURE REPRODUCED]'
            vrep.add(lvl, 'arena_gate_material', msg, g['seed'])
    res['static_validation'] = [vars(f) for f in vrep.findings]

    # ---------------- runtime emulation with piqueserver 1.4.2 code
    res['runtime'] = runtime_checks(data, mk)

    # ---------------- metadata import, exactly as piqueserver map.py would
    mod = check_map_txt(txt_path)

    class _Team:  # minimal stand-in
        def __init__(self, i): self.id = i

    class _Conn:
        def __init__(self, i): self.team = _Team(i)
    res['txt_import'] = {
        'name': mod.name, 'extensions': {k: str(v) for k, v in mod.extensions.items()},
        'spawn_blue_sample': mod.get_spawn_location(_Conn(0)),
        'spawn_spectator': mod.get_spawn_location(_Conn(-1)),
        'entities': {i: mod.get_entity_location(_Team(0), i) for i in range(4)},
    }
    res['piqueserver_map_loader'] = piqueserver_map_load(out_dir, scene.name)

    # ---------------- renders
    crop = mk['crop']
    imgs = {'top': top_down(back, crop=crop, scale=3)}
    for v in range(4):
        imgs[f'iso{v}'] = isometric(back, crop=crop, view=v, s=4)
    for k, im in imgs.items():
        im.save(os.path.join(out_dir, f'{scene.name}_{k}.png'))
    contact_sheet([imgs['top'], imgs['iso0'], imgs['iso2']],
                  ['top-down (north up, x right)', 'isometric view 0', 'isometric view 2 (rotated 180)']
                  ).save(os.path.join(out_dir, f'{scene.name}_sheet.png'))
    top_down(back).save(os.path.join(out_dir, f'{scene.name}_fullmap.png'))
    res['seconds'] = round(time.time() - t, 1)
    json.dump(res, open(os.path.join(out_dir, 'validation.json'), 'w'), indent=1, default=str)
    print(json.dumps(res, indent=1, default=str))
    return res


def runtime_checks(data, mk):
    """Run real piqueserver 1.4.2 code paths against the exported bytes."""
    from pyspades.vxl import VXLData
    out = {}

    # 1. collapse rule: check_node on floating slab vs grounded pillar
    m = VXLData(io.BytesIO(data))
    out['check_node_float_slab'] = m.check_node(271, 231, 44, False)     # >0 => floating size
    out['check_node_diag_block'] = m.check_node(289, 230, 56, False)
    out['check_node_pillar'] = m.check_node(256, 254, 50, False)         # 0 => grounded

    # 2. griefing vector: build a "player" block under the authored floating slab, destroy it.
    #    destroy_point -> check_node(destroy=True) on neighbours: removes the authored slab too.
    m = VXLData(io.BytesIO(data))
    built = m.build_point(271, 231, 45, (10, 10, 10))
    removed = m.destroy_point(271, 231, 45)
    out['grief_floating_authored'] = {'player_block_built': built, 'voxels_removed': removed,
                                      'slab_still_present': bool(m.get_solid(271, 231, 44))}

    # 3. redundancy: destroying one pillar voxel vs a full pillar layer under the roof
    m = VXLData(io.BytesIO(data))
    one = m.destroy_point(256, 254, 52)
    m = VXLData(io.BytesIO(data))
    total = 0
    for x in range(254, 259):
        for y in range(252, 257):
            total += m.destroy_point(x, y, 52)
    out['pillar_one_voxel_removed_count'] = one
    out['pillar_full_layer_removed_count'] = total
    out['roof_after_layer_cut'] = bool(m.get_solid(256, 254, 46))

    # 4. arena: run the real Gate class from piqueserver/game_modes/arena.py
    from piqueserver.game_modes import arena
    from pyspades import world

    class _P:
        pass
    gates = {}
    for g in mk['gates']:
        p = _P()
        p.map = VXLData(io.BytesIO(data))
        gate = arena.Gate(*g['seed'], p)
        n = 0
        for (a, b) in gate.blocks:
            n += len(world.cube_line(*(a + b)))
        # emulate destroy_gate on the map: does the opening become passable?
        for (a, b) in gate.blocks:
            for pt in world.cube_line(*(a + b)):
                p.map.remove_point(*pt)
        sx, sy, sz = g['seed']
        y_layers = {'gate_C_three_thick': (288, 289, 290)}.get(g['name'], (sy,))
        still = sum(bool(p.map.get_solid(x, y, z)) for x in range(302, 307) for y in y_layers for z in range(50, 58))
        gates[g['name']] = {'selected_blocks': n, 'support_blocks': len(gate.support_blocks),
                            'gate_color': gate.color, 'voxels_left_in_opening_after_destroy': still}
    out['arena_gate_class'] = gates

    # 5. push: classify swatch colours with push.py's own functions (default team colours)
    from piqueserver.game_modes import push
    blue_hls, green_hls = push.byte_rgb_to_hls((0, 0, 255)), push.byte_rgb_to_hls((0, 255, 0))
    cls = {}
    for name, rgb_ in {'red': (200, 40, 40), 'teal': (60, 170, 190), 'pure_blue_TEAM1_HS': (0, 0, 120),
                       'gate': mk['gate_rgb']}.items():
        h = push.byte_rgb_to_hls(rgb_)
        cls[name] = {'blue_team_block': push.compare_hs(h, blue_hls),
                     'green_team_block': push.compare_hs(h, green_hls)}
    out['push_colour_classification'] = cls
    return out


def piqueserver_map_load(out_dir, name):
    """Load .vxl + .txt through piqueserver.map.Map (the server's own loader)."""
    from piqueserver.map import Map, RotationInfo
    try:
        mp = Map(RotationInfo(name), out_dir)
        return {'ok': True, 'name': mp.name, 'author': mp.author,
                'has_get_spawn_location': mp.get_spawn_location is not None,
                'has_get_entity_location': mp.get_entity_location is not None,
                'extension_keys': sorted(mp.extensions),
                'data_get_z_200_260': mp.data.get_z(200, 260)}
    except Exception as e:  # noqa: BLE001
        return {'ok': False, 'error': repr(e)}
