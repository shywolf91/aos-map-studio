"""Generate a piqueserver map metadata file (<map>.txt).

Only attributes read by piqueserver 1.4.2 piqueserver/map.py Map.load_information() are emitted:
    name, version, author, description, extensions, time_limit, cap_limit, fog,
    get_spawn_location(connection), get_entity_location(team, entity_id),
    is_indestructable(protocol, x, y, z), on_block_destroy(connection, x, y, z, mode)
(`fog` is read by piqueserver/server.py on map change.)

Hook semantics (source-verified):
  * get_spawn_location(connection) -> (x, y, z) or None (None = default spawn). z is the voxel the
    player stands on; pyspades player.spawn() subtracts 2.4 to get the eye position.
  * get_entity_location(team, entity_id) -> (x, y, z) or None. entity ids from
    pyspades.constants: BLUE_FLAG=0, GREEN_FLAG=1, BLUE_BASE=2, GREEN_BASE=3. Note the first
    argument is the Team object (FeatureTeam.get_entity_location passes `self`).
  * team.id: 0 = team1 (blue), 1 = team2 (green), -1 = spectator.
  * on_block_destroy: ANY falsy return (incl. None) DENIES the destroy - we never emit it by default.
  * Game modes such as push/babel/arena REPLACE get_spawn_location/get_entity_location in their
    on_map_change; then the mode's extension keys are what matter, not these hooks.
"""
from __future__ import annotations

import pprint


def map_txt(*, name, author, description, version='1.0', extensions=None, spawns=None,
            entities=None, fog=None, time_limit=None, cap_limit=None, header=None) -> str:
    lines = ['# Generated by aosmap - piqueserver 1.4.2 map metadata', '']
    if header:
        lines += [f'# {h}' for h in header.splitlines()] + ['']
    lines += [f'name = {name!r}', f'version = {version!r}', f'author = {author!r}',
              f'description = {description!r}']
    if fog is not None:
        lines.append(f'fog = {tuple(fog)!r}')
    if time_limit is not None:
        lines.append(f'time_limit = {time_limit!r}')
    if cap_limit is not None:
        lines.append(f'cap_limit = {cap_limit!r}')
    lines += ['', 'extensions = ' + pprint.pformat(extensions or {}, width=100, sort_dicts=False)]
    if spawns:
        lines += ['', 'import random', '',
                  '# team.id -> list of (x, y, z_floor_voxel)',
                  'SPAWNS = ' + pprint.pformat({int(k): [tuple(p) for p in v] for k, v in spawns.items()},
                                               width=100), '',
                  'def get_spawn_location(connection):',
                  '    points = SPAWNS.get(connection.team.id)',
                  '    if not points:',
                  '        return None',
                  '    return random.choice(points)']
    if entities:
        lines += ['', '# entity id (BLUE_FLAG=0, GREEN_FLAG=1, BLUE_BASE=2, GREEN_BASE=3) -> (x, y, z)',
                  'ENTITIES = ' + pprint.pformat({int(k): tuple(v) for k, v in entities.items()}, width=100),
                  '', 'def get_entity_location(team, entity_id):',
                  '    return ENTITIES.get(entity_id)']
    return '\n'.join(lines) + '\n'


def check_map_txt(path):
    """Import the .txt the same way piqueserver map.py does and return the module (raises on error)."""
    import importlib.machinery
    import importlib.util
    loader = importlib.machinery.SourceFileLoader('aosmap_check_meta', str(path))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod
