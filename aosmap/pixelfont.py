W, H = 5, 7


def text_width(s, spacing=1):
    return len(s) * (W + spacing) - spacing if s else 0


def text_mask(lines, spacing=1, line_gap=3):
    width = max(text_width(l, spacing) for l in lines)
    height = len(lines) * H + (len(lines) - 1) * line_gap
    m = np.zeros((width, height), bool)
    for li, line in enumerate(lines):
        y0 = li * (H + line_gap)
        for ci, ch in enumerate(line):
            g = _G.get(ch, _G[' '])
            x0 = ci * (W + spacing)
            for r, row in enumerate(g):
                for c, px in enumerate(row):
                    if px == '#':
                        m[x0 + c, y0 + r] = True
    return m
