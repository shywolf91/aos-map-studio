def text_mask(text, scale=1, spacing=1):
    cols = []
    for ch in text.upper():
        g = np.array([[c == '1' for c in row] for row in G[ch]], bool)
        cols.append(g)
        cols.append(np.zeros((7, spacing), bool))
    m = np.concatenate(cols[:-1], axis=1)
    return np.kron(m, np.ones((scale, scale), bool))
